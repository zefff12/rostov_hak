RED = RGBColor(0xC0, 0x00, 0x00)


def _para(doc, text="", bold=False, align=None, size=13, color=None, indent=True, space_after=0):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(0)
    pf.line_spacing = 1.0
    if align is not None:
        p.alignment = align
    elif indent:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pf.first_line_indent = Cm(1.25)
    if text:
        run = p.add_run(text)
        run.bold = bold
        run.font.size = Pt(size)
        if color:
            run.font.color.rgb = color
    return p


def build_docx(module: Module, r: dict, module_meta: dict | None = None) -> str:
    """Формирует файл проекта по правилам Метод. рекомендаций (п. 3.3): без грифа утверждения,
    пометки «МОДУЛЬНЫЙ ДОКУМЕНТ», линий и номеров примечаний; служебные зоны сохранены."""
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(13)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    sec = doc.sections[0]
    sec.left_margin, sec.right_margin = Cm(3), Cm(1.5)
    sec.top_margin, sec.bottom_margin = Cm(2), Cm(2)

    C = WD_ALIGN_PARAGRAPH.CENTER
    _para(doc, "НАИМЕНОВАНИЕ ОРГАНИЗАЦИИ", bold=True, align=C, space_after=6)
    _para(doc, r["kind"], bold=True, align=C, size=14, space_after=6)
    _para(doc, "ДАТА / РЕГИСТРАЦИОННЫЙ НОМЕР (НЕ УДАЛЯТЬ)", align=C, color=RED, size=10)
    _para(doc, "г. Москва", align=C, space_after=12)
    _para(doc, r["title"], bold=True, align=C, space_after=12)
    _para(doc, r["preamble"])
    _para(doc, r["verb"], bold=False, indent=False)
    for n, p in enumerate(r["points"], 1):
        if isinstance(p, tuple):
            head, sub = p
            _para(doc, f"{n}. {head}")
            if sub == "TABLE":
                t = doc.add_table(rows=1, cols=2)
                t.style = "Table Grid"
                t.alignment = WD_TABLE_ALIGNMENT.CENTER
                for c, h in zip(t.rows[0].cells, r["table"]["header"]):
                    c.text = h
                    c.paragraphs[0].runs[0].bold = True
                for role, person in r["table"]["rows"]:
                    cells = t.add_row().cells
                    cells[0].text, cells[1].text = role, person
            else:
                for j, s in enumerate(sub, 1):
                    _para(doc, s if s.startswith("•") else f"{n}.{j}. {s}")
        else:
            _para(doc, f"{n}. {p}")
    _para(doc, "", space_after=18)
    if r["signer"]:
        t = doc.add_table(rows=1, cols=2)
        t.cell(0, 0).text = r["signer_pos"]
        t.cell(0, 1).text = r["signer"]
        t.cell(0, 1).paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.RIGHT
    _para(doc, "ВИЗУАЛИЗАЦИЯ ЭП (НЕ УДАЛЯТЬ)", align=C, color=RED, size=10)

    # Длинный случайный суффикс: ссылка на файл не угадывается перебором.
    name = f"{module.id}_{dt.datetime.now():%Y%m%d_%H%M%S}_{uuid.uuid4().hex}.docx"
    path = config.GENERATED_DIR / name
    doc.save(path)
    return name


