def semantic_checks(module: Module, v: dict) -> list[str]:
    """Проверки по «Общим правилам» модулей."""
    warns = []
    if module.id == "is_commissioning":
        bd = parse_date(v.get("basis_doc", ""))
        if bd and v.get("start_date") and dt.date.fromisoformat(v["start_date"]) < bd:
            warns.append("Дата ввода раньше даты документа о готовности (примечание 8 к модулю).")
    if module.id == "handover":
        rep = v.get("representative", "").lower()
        for k in ("giver", "receiver"):
            surname = (re.findall(r"[А-ЯЁ][а-яё]+(?=\s+[А-ЯЁ]\.)", v.get(k, "")) or [""])[0].lower()[:5]
            if surname and surname in rep:
                warns.append("Представитель Организации, похоже, совпадает со сдающим или принимающим "
                             "(«Общие правила» модуля).")
    if module.id == "internal_audit":
        try:
            ds = [dt.date.fromisoformat(v[k]) for k in ("date_from", "date_to", "report_date", "plan_date")]
            if not (ds[0] <= ds[1] <= ds[2] <= ds[3]):
                warns.append("Проверьте последовательность дат: начало ≤ окончание ≤ отчет ≤ план мероприятий.")
        except (KeyError, ValueError):
            pass
    if module.id == "working_group":
        try:
            if dt.date.fromisoformat(v["deadline"]) < dt.date.today():
                warns.append("Срок для рабочей группы уже прошел.")
        except (KeyError, ValueError):
            pass
    return warns
