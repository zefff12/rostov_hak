def parse_date(text: str) -> dt.date | None:
    t = text.strip().lower().replace("«", "").replace("»", "").replace("г.", "").replace("года", "").strip()
    m = re.search(r"(\d{1,2})[./-](\d{1,2})[./-](\d{2,4})", t)
    if m:
        d, mo, y = map(int, m.groups())
        y = y + 2000 if y < 100 else y
        try:
            return dt.date(y, mo, d)
        except ValueError:
            return None
    m = re.search(r"(\d{4})-(\d{2})-(\d{2})", t)
    if m:
        return dt.date(*map(int, m.groups()))
    m = re.search(r"(\d{1,2})\s+([а-я]+)\s+(\d{4})", t)
    if m:
        mon = next((i for i, n in enumerate(MONTHS, 1) if m.group(2)[:3] == n[:3]), None)
        if mon:
            try:
                return dt.date(int(m.group(3)), mon, int(m.group(1)))
            except ValueError:
                return None
    return None


def fmt_date(d: dt.date) -> str:
    return f"«{d.day:02d}» {MONTHS[d.month - 1]} {d.year} г."


def normalize(f: Field, raw: str) -> tuple[object | None, str | None]:
    """Приводит ответ пользователя к значению поля. Возвращает (значение, ошибка)."""
    s = raw.strip()
    # Точку в конце убираем только после обычного слова — инициалы «П. П.» сохраняются.
    if s.endswith(".") and not re.search(r"(^|[\s.])[А-ЯЁA-Z]\.$", s):
        s = s[:-1].rstrip()
    if not f.required and s.lower() in ("пропустить", "нет", "не нужно", "-", "—", "skip"):
        return "", None
    if f.kind == "date":
        d = parse_date(s)
        return (d.isoformat(), None) if d else (None, "Не распознал дату. Укажите в формате ДД.ММ.ГГГГ, например 01.12.2026.")
    if f.kind == "choice":
        for o in f.options:
            if s.lower().startswith(o[:5]):
                return o, None
        if re.search(r"нов|впервые|созда|разраб", s.lower()):
            return f.options[0], None
        if re.search(r"верс|доработ|модиф|измен", s.lower()):
            return f.options[-1], None
        return None, "Выберите один из вариантов: " + " / ".join(f.options)
    if f.kind == "yesno":
        if re.match(r"^(да|yes|связан|требуется|конечно|ага)", s.lower()):
            return True, None
        if re.match(r"^(нет|no|не )", s.lower()):
            return False, None
        return None, "Ответьте «да» или «нет»."
    if f.kind == "list":
        items = [x.strip(" ;,.") for x in re.split(r"\n|;", s) if x.strip(" ;,.")]
        return (items, None) if items else (None, "Укажите хотя бы одно значение.")
    if f.kind == "control" and re.search(r"за собой|подписант|сам", s.lower()):
        return CONTROL_SELF, None
    if not s:
        return None, "Значение не может быть пустым."
    return s, None


def inflect_head(phrase: str, case: str) -> str:
    """Склоняет начало наименования до первого существительного включительно
    («Положение о …» → «Положения о …»)."""
    if not _MORPH:
        return phrase
    words = phrase.split(" ")
    out = []
    for i, w in enumerate(words):
        core = re.sub(r"[^\w-]", "", w)
        p = _MORPH.parse(core)[0] if core else None
        if not p or not ({"NOUN", "ADJF", "PRTF"} & {p.tag.POS}):
            out.extend(words[i:])
            break
        form = p.inflect({case})
        new = form.word if form else core
        if core[:1].isupper():
            new = new[:1].upper() + new[1:]
        out.append(w.replace(core, new))
        if p.tag.POS == "NOUN":
            out.extend(words[i + 1:])
            break
    return " ".join(out)


