def to_text(r: dict) -> str:
    """Плоский текст проекта (для предпросмотра в чате)."""
    out = [r["kind"], "ДАТА / РЕГИСТРАЦИОННЫЙ НОМЕР (НЕ УДАЛЯТЬ)", "г. Москва", "", f"**{r['title']}**", "",
           r["preamble"], r["verb"]]
    for n, p in enumerate(r["points"], 1):
        if isinstance(p, tuple):
            head, sub = p
            out.append(f"{n}. {head}")
            if sub == "TABLE":
                for role, person in r["table"]["rows"]:
                    out.append(f"   {role + ': ' if role else '   '}{person}")
            else:
                for j, s in enumerate(sub, 1):
                    out.append(f"   {s}" if s.startswith("•") else f"{n}.{j}. {s}")
        else:
            out.append(f"{n}. {p}")
    if r["signer"]:
        out += ["", f"{r['signer_pos']}    {r['signer']}"]
    out.append("ВИЗУАЛИЗАЦИЯ ЭП (НЕ УДАЛЯТЬ)")
    return "\n".join(out)


