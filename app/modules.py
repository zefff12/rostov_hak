CONTROL_SELF = "оставляю за собой"


@dataclass
class Field:
    key: str
    question: str
    hint: str = ""
    example: str = ""
    kind: str = "text"  # text | date | choice | list | yesno | control
    required: bool = True
    options: list[str] = field(default_factory=list)
    note: int | None = None  # номер примечания в модуле

    @property
    def label(self) -> str:
        return re.split(r"[?:.(—]", self.question)[0].strip()


@dataclass
class Module:
    id: str
    title: str
    doc_type: str  # приказ | распоряжение
    file: str
    keywords: str
    matrix_row: int
    signer_pos: str
    fields: list[Field]
    conditions: dict = field(default_factory=dict)  # поле -> ключ условия Матрицы


def F(*a, **kw):
    return Field(*a, **kw)


